import { googletag } from 'ad-tag/types/googletag';
import { AdPipelineContext, InitStep, mkInitStep } from 'ad-tag/ads/adPipeline';
import { isPlainObject } from 'ad-tag/util/objectUtils';
import { findGoogletagSlot } from 'ad-tag/ads/findGoogletagSlot';
import { prebidjs } from 'ad-tag/types/prebidjs';

export type PassbackMessage = {
  /**
   */
  event: 'h5.adunit.passback';

  /**
   * the domId of the ad slot that should be refreshed.
   *
   * This is used as a fallback if the `adUnitPath` is not set.
   * The `adUnitPath` should be prefered as it is more generic
   * and can be auto-generated by GAM.
   */
  domId?: string;

  /**
   * the adUnitPath of the ad slot that should be refreshed.
   *
   * If set the adUnitPath will be used to search of the ad slot
   * and the DOM ID is being ignored.
   */
  adUnitPath?: string;

  /**
   * name of the advertisier who is the origin for the passback to being triggered
   */
  passbackOrigin: string;
};

export type RefreshAdUnitMessage = {
  event: 'h5.adunit.refresh';
  domId: string;
};

/**
 * Sent by a creative that wants the page's content - the headline it is rendered next to, the
 * author of the post, the content language. The page answers with an `Ortb2ResponseMessage`.
 *
 * @see Ortb2ResponseMessage
 */
export type Ortb2Message = {
  event: 'h5.ortb2';
};

/**
 * The page's answer to an `Ortb2Message`, posted to the window that asked and to no other.
 *
 * Carries the OpenRTB 2.6 first party data of the **current** page - the static
 * `targeting.ortb2` and the runtime half set via `moli.setConfig({ ortb2 })`, deep merged.
 *
 * It carries ortb2 and nothing else: no key-values, no labels. Audience segment ids and score
 * level are page targeting a creative has no business reading.
 */
export type Ortb2ResponseMessage = {
  event: 'h5.ortb2.response';
  ortb2: prebidjs.firstpartydata.PrebidFirstPartyData;
};

export type BridgeProtocol = PassbackMessage | RefreshAdUnitMessage | Ortb2Message;

const parseMessageData = (data: any): BridgeProtocol | null => {
  try {
    const message: BridgeProtocol | null =
      typeof data === 'string' ? JSON.parse(data) : isPlainObject(data) ? data : null;

    switch (message?.event) {
      case 'h5.adunit.passback':
        return message.passbackOrigin && (message.domId || message.adUnitPath) ? message : null;
      // neither carries a payload to validate
      case 'h5.adunit.refresh':
      case 'h5.ortb2':
        return message;
      default:
        // if this is not a valid message we return null
        return null;
    }
  } catch (err) {
    // invalid json - another iframe message was posted
    return null;
  }
};

/**
 * Refresh message are sent by third party creatives to indicate that they have no ads to show.
 * Calls the backfill ad slot to refresh the ad slot.
 *
 * @param message post message data
 * @param context
 */
const handleRefresh = (message: RefreshAdUnitMessage, context: AdPipelineContext): void => {
  const backfillMoliSlot = context.config__.slots.find(
    slot => slot.domId === message.domId && slot.behaviour.loaded === 'backfill'
  );
  const adSlot = findGoogletagSlot(message, context.window__.googletag);
  if (backfillMoliSlot && adSlot) {
    context.logger__.debug('bridge', `Refresh ad slot ${message.domId}`);
    context.window__.googletag.destroySlots([adSlot]);
    context.window__.moli
      .refreshAdSlot(message.domId, { loaded: 'backfill' })
      .catch(e => context.logger__.error('bridge', `failed to refresh ${message.domId}`, e));
  }
};

/**
 * Passback message are sent by third party creatives to indicate that they don't have any ads to show.
 *
 * The ad slot will be refreshed if a window.postMessage event is being sent from
 * a creative identifying the ad slot by domId or ad unit path. In additional key value `passback:true` will
 * be set indicating this is a passback request. The rest of the key-values will be untouched
 * keeping the prebid / a9 auction key-values.
 *
 *
 * ## Example creative snippet
 *
 * This is an example of how a passback function could look like in a creative.
 * Note that you can either use the `adUnitPath` or the `domId` of the slot.
 *
 * `adUnitPath` is not yet fully supported, when using variables in the ad unit path.
 *
 * ```
 * var passbackCallback = function() {
 *   var request = JSON.stringify({
 *     type: 'passback',
 *     adUnitPath: '%%ADUNIT%%' ,
 *     passbackOrigin: '[ADVERTISER-NAME]'
 *   });
 *   try {
 *     // first try to post a message on the top most window
 *     window.top.postMessage(request, '*');
 *   } catch (_) {
 *     // best-effort postMessage
 *     window.postMessage(request, '*');
 *   }
 * }
 * ```
 *
 * Default is `false`
 *
 * @param message
 * @param context
 */
const handlePassback = (message: PassbackMessage, context: AdPipelineContext): void => {
  const adSlot = findGoogletagSlot(message, context.window__.googletag);
  const passbackKey = 'passback';
  // only refresh if the ad slot is available and has not yet been marked as passback
  if (adSlot && adSlot.getTargeting(passbackKey).length === 0) {
    context.logger__.debug('passback', `Process passback for ad slot ${adSlot.getAdUnitPath()}`);
    adSlot.setTargeting(passbackKey, 'true');
    adSlot.setTargeting('passbackOrigin', message.passbackOrigin);

    // previously we had changeCorrelator: true (see GD-1615), but this hadn't the intended effect
    // so we removed it (see GD-1696)
    context.window__.googletag.pubads().refresh([adSlot]);
  }
};

/**
 * Answers a creative that asked for the page's ortb2.
 *
 * ## Why the value is read from the window and not from the context
 *
 * The bridge init step is memoised, so the `AdPipelineContext` this listener closes over is the
 * one from the *first* ad request and never changes. A single-page-app navigation builds a fresh
 * runtime config, so reading the captured context would hand the creative the *previous* page's
 * content. `window.moli.getPageTargeting()` is the only accessor that sees the current page.
 *
 * ## Why there is no origin check
 *
 * Consistent with `h5.adunit.passback` and `h5.adunit.refresh`, which have none either. A
 * sandboxed SafeFrame has the origin `null`, so an allow-list would lock out exactly the
 * creatives this exists for. What keeps the data contained instead is the reply target: it goes
 * to the window that asked and is never broadcast, and it carries ortb2 and nothing else.
 *
 * The accepted cost is that the page answers any iframe that asks, including third party
 * creatives in other slots - which is why `ortb2` is no place for anything that should not be
 * readable by a creative.
 *
 * The message itself carries no payload, so this takes the asking window rather than the parsed
 * message - that window is the only thing the handler needs.
 *
 * @param source the window that asked, taken from the message event's `source`
 * @param context
 * @see docs/adr/0016-ortb2-is-the-page-content-channel.md
 */
const handleOrtb2 = (source: Window | null, context: AdPipelineContext): void => {
  if (!source) {
    context.logger__.debug('bridge', 'ortb2 request without a source window - ignoring');
    return;
  }
  const response: Ortb2ResponseMessage = {
    event: 'h5.ortb2.response',
    // read live - see the note above
    ortb2: context.window__.moli.getPageTargeting().ortb2 ?? {}
  };
  context.logger__.debug('bridge', 'answering ortb2 request');
  // '*' rather than event.origin: a sandboxed SafeFrame's origin is the string 'null', which no
  // postMessage target origin ever matches. The reply is contained by its target window, not by
  // its target origin.
  source.postMessage(response, '*');
};

export const bridgeInitStep = (): InitStep =>
  mkInitStep('bridge', (context: AdPipelineContext) => {
    if (context.config__.bridge?.enabled) {
      context.logger__.debug('bridge', 'add message listener');
      context.window__.addEventListener('message', (event: MessageEvent<BridgeProtocol>) => {
        const message = parseMessageData(event.data);
        if (message) {
          switch (message.event) {
            case 'h5.adunit.passback':
              handlePassback(message, context);
              break;
            case 'h5.adunit.refresh':
              handleRefresh(message, context);
              break;
            case 'h5.ortb2':
              // `MessageEventSource` also covers MessagePort and ServiceWorker, whose
              // postMessage has a different signature. A creative always posts from a window.
              handleOrtb2(event.source as Window | null, context);
              break;
          }
        }
      });
    }
    return Promise.resolve();
  });
